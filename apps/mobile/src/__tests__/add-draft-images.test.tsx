import { act, renderHook } from '@testing-library/react-native';
import type { SharedImage } from '@/domain/image-share';
const mockRelease = jest.fn();
const mockRead = jest.fn();
jest.mock('@/share/smart-clipboard', () => ({ readSmartClipboard: () => mockRead(), releaseOwnedClipboardImage: (image: unknown) => mockRelease(image) }));
import { useAddDraft } from '@/features/add/use-add-draft';
const image = (id: string): SharedImage => ({ uri: `file:///cache/${id}.png`, mimeType: 'image/png', fileName: null });
beforeEach(() => jest.clearAllMocks());
it('declines candidate, retains image through failed save and mode changes, and releases removed source', async () => {
 const first = image('first'); const candidate = image('candidate');
 const { result, unmount } = await renderHook(() => useAddDraft());
 await act(() => result.current.offer('caption', first));
 await act(() => result.current.offer('other', candidate));
 expect(mockRelease).not.toHaveBeenCalled();
 await act(() => result.current.keep());
 expect(mockRelease).toHaveBeenCalledWith(candidate);
 mockRelease.mockClear();
 let release!: () => void;
 await act(() => { release = result.current.retainImage(first); });
 // A failed save finishes, leaving the same preview available for retry.
 await act(() => release());
 await act(() => result.current.changeMode('note'));
 expect(mockRelease).not.toHaveBeenCalled();
 await act(() => result.current.changeMode('image'));
 expect(result.current.draft.image).toBe(first);
 await act(() => result.current.update({ image: undefined }));
 expect(mockRelease).toHaveBeenCalledWith(first);
 await unmount();
 expect(mockRelease).toHaveBeenCalledTimes(1);
});
it('retains an in-flight save source after unmount until its last use finishes', async () => {
 const source = image('saving');
 const { result, unmount } = await renderHook(() => useAddDraft());
 await act(() => result.current.offer('', source));
 const release = result.current.retainImage(source);
 await unmount();
 expect(mockRelease).not.toHaveBeenCalled();
 release(); release();
 expect(mockRelease).toHaveBeenCalledTimes(1);
 expect(mockRelease).toHaveBeenCalledWith(source);
});
it('releases late clipboard results after unmount and results invalidated by editing', async () => {
 let resolve!: (value: { text: string; image: SharedImage }) => void;
 mockRead.mockImplementation(() => new Promise(done => { resolve = done; }));
 const { result, unmount } = await renderHook(() => useAddDraft());
 let read!: Promise<void>;
 await act(() => { read = result.current.paste(); });
 await act(() => result.current.update({ memo: 'User edit' }));
 const stale = image('stale');
 await act(async () => { resolve({ text: '', image: stale }); await read; });
 expect(mockRelease).toHaveBeenCalledWith(stale);
 await act(() => { read = result.current.paste(); });
 await unmount();
 const late = image('late');
 await act(async () => { resolve({ text: '', image: late }); await read; });
 expect(mockRelease).toHaveBeenCalledWith(late);
});
it('replacement releases previous image while successful completion releases the accepted draft', async () => {
 const first = image('first'); const next = image('next');
 const { result, unmount } = await renderHook(() => useAddDraft());
 await act(() => result.current.offer('', first));
 await act(() => result.current.offer('', next));
 await act(() => result.current.replace());
 expect(mockRelease).toHaveBeenCalledWith(first);
 expect(mockRelease).not.toHaveBeenCalledWith(next);
 await act(() => result.current.releaseImages());
 expect(mockRelease).toHaveBeenCalledWith(next);
 await unmount();
 expect(mockRelease).toHaveBeenCalledTimes(2);
});
it('disposes rejected oversized images and late image-reader results without replacing the current draft', async () => {
 const source = image('active'); const oversized = image('oversized');
 const { result, unmount } = await renderHook(() => useAddDraft());
 await act(() => result.current.offer('caption', source));
 await act(() => result.current.offer('x'.repeat(10_001), oversized));
 expect(result.current.status).toBe('textTooLong');
 expect(result.current.draft.image).toBe(source);
 expect(mockRelease).toHaveBeenCalledWith(oversized);
 let resolve!: (value: SharedImage) => void;
 let read!: Promise<void>;
 await act(() => { read = result.current.receiveImage(() => new Promise(done => { resolve = done; }), ''); });
 await unmount();
 const late = image('late-image-reader');
 await act(async () => { resolve(late); await read; });
 expect(mockRelease).toHaveBeenCalledWith(late);
 expect(mockRelease).toHaveBeenCalledWith(source);
});
